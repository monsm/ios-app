// ---------- 44 动作页: 一批改动的落点说明 ----------
struct ChangeBatchView: View {
    let batch: String
    @EnvironmentObject var app: AppState
    @Environment(\.dismiss) private var dismiss
    private var items: [ChangeEntry] { Changelog.entries.filter { $0.batch == batch } }

    var body: some View {
        List {
            // 2026-10-15 走查: 原先这里是「字面 第 + batch」。而 batch 的取值**全部**形如「第X批」
            // —— 行首锚定的两条计数相等就是证据 (用不带行首锚的 `grep -o` 会把本段注释自己数进去):
            //   grep -c '^[[:space:]]*batch: "'        App/UI/ChangelogView.swift  ⇒ 82
            //   grep -c '^[[:space:]]*batch: "第.*批"' App/UI/ChangelogView.swift  ⇒ 82
            // ⇒ 每一页标题都渲染成「第第一百八十七批落了这些」。去掉前面那个字面的「第」。
            Section("\(batch)落了这些") {
                ForEach(items) { e in
                    VStack(alignment: .leading, spacing: DS.Space.xxs) {
                        Text(e.title).font(.subheadline.weight(.medium))
                        mdText(e.detail).font(.footnote).foregroundStyle(DS.Palette.textSub)
                            .fixedSize(horizontal: false, vertical: true)
                        Text("功能编号 #" + String(e.id) + " — 可在 docs/IDEA-BANK.md 查到原句，"
                             + "在覆盖表里查到实现证据。")
                            .font(.caption2).foregroundStyle(DS.Palette.textSub)
                        // 44 动作出口: 条目原文里第一个提到的页面名 = 落点, 点按钮真的走到那个 Tab
                        // (先 pop 回设置列表再切)。一个页面名都没提的条目不摆按钮 —— 指错路比没路更糟。
                        if let goto = Self.landingTab(e) {
                            Button("去\(goto.0)页看看") {   // 44 页看看
                                dismiss()
                                app.requestTab(goto.1)
                            }
                            .font(.caption.weight(.medium))
                            .foregroundStyle(DS.Palette.accentText)
                            .buttonStyle(.plain)
                            .frame(minHeight: DS.Hit.min, alignment: .leading)
                        }
                    }
                }
            }
        }
        .navigationTitle(batch)
        .scrollContentBackground(.hidden)
        .dsScreenBackground()
    }

    /// 44 落点判定: 关键词 → Tab 序号 (device0/credentials1/records2/settings3, 与 170 那张同一张表)。
    /// 取标题+正文里出现位置最靠前的一个词; 命中不到返回 nil。
    private static func landingTab(_ e: ChangeEntry) -> (String, Int)? {
        let s = e.title + e.detail
        let cands: [(String, Int)] = [("设置", 3), ("诊断", 3), ("记录", 2), ("凭证", 1),
                                      ("成员", 1), ("设备", 0), ("圆盘", 0)]
        var best: (String, Int)?
        var bestPos = Int.max
        for (kw, tab) in cands {
            guard let r = s.range(of: kw) else { continue }
            let pos = s.distance(from: s.startIndex, to: r.lowerBound)
            if pos < bestPos { bestPos = pos; best = (kw, tab) }
        }
        return best
    }
}
